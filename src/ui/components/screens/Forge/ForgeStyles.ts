export const getStatTheme = (label: string) => {
    const upper = label.toUpperCase();
    if (upper.includes('ЗАЩИТА') || upper.includes('DEFENSE')) {
        return {
            border: '1.5px solid rgba(96, 165, 250, 0.65)',
            bg: 'rgba(16, 24, 40, 0.95)',
            shadow: '0 8px 24px rgba(59, 130, 246, 0.25)',
            textColor: '#60a5fa',
        };
    }
    if (upper.includes('ЗДОРОВЬЕ') || upper.includes('HP') || upper.includes('HEALTH')) {
        return {
            border: '1.5px solid rgba(248, 113, 113, 0.65)',
            bg: 'rgba(40, 16, 16, 0.95)',
            shadow: '0 8px 24px rgba(239, 68, 68, 0.25)',
            textColor: '#f87171',
        };
    }
    if (upper.includes('ПРОБИВАНИЕ') || upper.includes('PENETRATION') || upper.includes('ПРОБИВ')) {
        return {
            border: '1.5px solid rgba(192, 132, 252, 0.65)',
            bg: 'rgba(32, 16, 40, 0.95)',
            shadow: '0 8px 24px rgba(168, 85, 247, 0.25)',
            textColor: '#c084fc',
        };
    }
    return {
        border: '1.5px solid rgba(240, 192, 64, 0.65)',
        bg: 'rgba(28, 20, 14, 0.95)',
        shadow: '0 8px 24px rgba(240, 192, 64, 0.25)',
        textColor: '#fcd34d',
    };
};

