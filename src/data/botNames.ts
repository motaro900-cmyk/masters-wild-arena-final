export const getRandomBotName = (): string => {
    const isMale = Math.random() < 0.65;
    if (isMale) {
        const first = FIRST_NAMES_MALE[Math.floor(Math.random() * FIRST_NAMES_MALE.length)];
        const last = LAST_NAMES_MALE[Math.floor(Math.random() * LAST_NAMES_MALE.length)];
        return `${first} ${last}`;
    } else {
        const first = FIRST_NAMES_FEMALE[Math.floor(Math.random() * FIRST_NAMES_FEMALE.length)];
        const last = LAST_NAMES_FEMALE[Math.floor(Math.random() * LAST_NAMES_FEMALE.length)];
        return `${first} ${last}`;
    }
};
